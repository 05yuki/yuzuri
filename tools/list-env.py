#!/usr/bin/env python3
"""Write docs/env.md: every environment variable the package reads, its default where the code gives one, and the files
that read it. `--check` exits 1 when docs/env.md differs from what the code says (tests/test_tables.py runs it)."""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
READ = re.compile(
    r"""(?:os\.environ\.get|os\.getenv|environ\.get|os\.environ\.setdefault)\(\s*["']([A-Z][A-Z0-9_]+)["']\s*(?:,\s*((?:[^()\n]|\([^()\n]*\)){0,80}?))?\)"""
    r"""|os\.environ\[\s*["']([A-Z][A-Z0-9_]+)["']\s*\]"""
    r"""|["']([A-Z][A-Z0-9_]+)["']\s+(?:not\s+)?in\s+os\.environ"""
)


def scan():
    seen = {}
    for top in ("python", "tools", "patches"):
        for d, _, fs in os.walk(os.path.join(ROOT, top)):
            for f in sorted(fs):
                if not f.endswith(".py") or f == "list-env.py":
                    continue
                p = os.path.join(d, f)
                rel = os.path.relpath(p, ROOT)
                for m in READ.finditer(open(p, encoding="utf-8").read()):
                    name = m.group(1) or m.group(3) or m.group(4)
                    e = seen.setdefault(name, {"defaults": set(), "files": set()})
                    e["files"].add(os.path.basename(rel))
                    if m.group(2):
                        e["defaults"].add(m.group(2).strip())
    return seen


def render(seen):
    out = ["# Environment variables", "",
           "Generated by `python3 tools/list-env.py`. Do not edit by hand.", "",
           "The launcher sets what a run needs. A variable here is a switch for a measurement or a diagnosis, "
           "not something a first run has to set.", "",
           "Default is the value the code falls back to. A dash means the code only checks whether it is set, "
           "or takes the default from elsewhere.", "",
           f"{len(seen)} names.", ""]
    groups = {}
    for name in sorted(seen):
        groups.setdefault(name.split("_")[0], []).append(name)
    for g in sorted(groups, key=lambda k: (-len(groups[k]), k)):
        out += [f"## {g}_", "", "| Name | Default | Read in |", "|---|---|---|"]
        for name in groups[g]:
            e = seen[name]
            d = " / ".join(sorted(x.replace("|", "\\|") for x in e["defaults"])) or "-"
            out.append(f"| `{name}` | `{d}` | {', '.join(sorted(e['files']))} |" if d != "-" else
                       f"| `{name}` | - | {', '.join(sorted(e['files']))} |")
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    text = render(scan())
    path = os.path.join(ROOT, "docs", "env.md")
    if "--check" in sys.argv:
        ok = os.path.isfile(path) and open(path, encoding="utf-8").read() == text
        print("docs/env.md matches the code" if ok else "docs/env.md is stale: run python3 tools/list-env.py")
        sys.exit(0 if ok else 1)
    open(path, "w", encoding="utf-8").write(text)
    print(f"wrote {path}")
